#!/usr/bin/env python3
"""Figure 3, one SVG per panel, for assembly by hand.

Same arrangement as fig1_panels.py and fig2_panels.py: these and the
assembled `fig3_platform.py` are built from one set of panel functions, so a
fix lands in both and they cannot drift.

Each panel is authored at the size it is meant to be placed at, in inches on
a 6.5 in page. Place at 100% and the 7 pt font floor holds. No panel letters
-- they belong to the layout; the filename carries the intended one.

Panel (a), the assembly-and-assay pipeline strip, is not emitted here: it is
Jason's `svg/wetlab_pipeline.svg` and is a schematic, not a data plot.

    uv run python paper/figures/fig3_panels.py
    -> paper/figures/svg/fig3_panels/*.svg
"""

import sys
from pathlib import Path

import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import fig3_platform as F3  # noqa: E402
from figio import save  # noqa: E402

SUB = "fig3_panels"

SIZES = {
    "fig3b_cascade": (2.10, 2.05),
    "fig3c_controls": (2.10, 2.05),
    "fig3d_parity": (2.20, 2.15),
    "fig3e_trace": (2.60, 2.05),
    "fig3f_scale": (3.00, 1.70),
    "fig3g_libraries": (6.50, 2.40),
}

MARGIN = {
    "fig3b_cascade": dict(left=0.260, right=0.985, top=0.975, bottom=0.165),
    "fig3c_controls": dict(left=0.300, right=0.985, top=0.890, bottom=0.165),
    # Aspect-equal axes: generous margins all round, because the box is
    # fitted inside whatever is left and a tight margin shrinks the plot
    # rather than the whitespace.
    "fig3d_parity": dict(left=0.235, right=0.985, top=0.975, bottom=0.165),
    "fig3e_trace": dict(left=0.195, right=0.985, top=0.975, bottom=0.175),
    "fig3f_scale": dict(left=0.230, right=0.985, top=0.965, bottom=0.215),
    "fig3g_libraries": dict(left=0.085, right=0.990, top=0.970, bottom=0.135),
}

WHAT = {
    "fig3b_cascade": "what survives each gate, library 3, from raw reads",
    "fig3c_controls": "positive-control raw rate per plate, per round",
    "fig3d_parity": "replicate 1 against replicate 2, per construct",
    "fig3e_trace": "one plate's worked traces, 4MU against time",
    "fig3f_scale": "assayed count against library size",
    "fig3g_libraries": "all three libraries by round, on one momi axis",
}


def _fig(stem):
    fig = plt.figure(figsize=SIZES[stem])
    gs = fig.add_gridspec(1, 1, **MARGIN[stem])
    return fig, fig.add_subplot(gs[0, 0])


def _write(fig, stem):
    save(fig, stem, dpi=900, tight=False, subdir=SUB)
    plt.close(fig)


def _manifest():
    out = [
        "# Figure 3, one SVG per panel",
        "",
        "Generated by `paper/figures/fig3_panels.py`. Each panel is authored",
        "at the size it is meant to be placed at on a 6.5 in page -- place at",
        "100% and the 7 pt font floor holds. No panel letters: they belong to",
        "the layout, and the filename carries the intended one.",
        "",
        "| file | size (in) | what it shows |",
        "|---|---|---|",
    ]
    for stem, (w, h) in SIZES.items():
        out.append(f"| `{stem}.svg` | {w:.2f} x {h:.2f} | {WHAT[stem]} |")
    out += [
        "",
        "Panel (a), the assembly-and-assay pipeline strip, is not here: it is",
        "`../wetlab_pipeline.svg` and is a schematic rather than a data plot.",
        "",
        "(b), (d) and (e) exist only because the raw plate reads were",
        "re-processed by `library_kinetics.py`. jq01's shipped tables are",
        "`processed_filtered_*` and one row per construct, so they carry",
        "neither the counts that were dropped nor the individual replicates.",
        "The re-processing reproduces their published values at Spearman",
        "0.990 with a median ratio of 1.000.",
        "",
        "**(b), (d) and (e) are library 3 only.** Library 2's raw reads do",
        "not survive in this layout -- only its processed tables do -- so the",
        "cascade, the parity plot and the worked trace are library-3",
        "quantities. (c), (f) and (g) cover all three.",
        "",
        "The assembled version is `../main/fig3_platform.svg`.",
        "",
    ]
    d = HERE / "svg" / SUB
    d.mkdir(parents=True, exist_ok=True)
    (d / "README.md").write_text("\n".join(out))


def main():
    snap, designs, reps, traces = F3.load()

    fig, ax = _fig("fig3b_cascade")
    F3.panel_cascade(ax, designs, reps)
    _write(fig, "fig3b_cascade")

    fig, ax = _fig("fig3c_controls")
    F3.panel_controls(ax, designs)
    _write(fig, "fig3c_controls")

    fig, ax = _fig("fig3d_parity")
    F3.panel_parity(ax, reps, designs)
    _write(fig, "fig3d_parity")

    fig, ax = _fig("fig3e_trace")
    F3.panel_trace(ax, traces, reps)
    _write(fig, "fig3e_trace")

    fig, ax = _fig("fig3f_scale")
    F3.panel_scale(ax, snap)
    _write(fig, "fig3f_scale")

    fig, ax = _fig("fig3g_libraries")
    F3.panel_libraries(ax, snap)
    _write(fig, "fig3g_libraries")

    _manifest()
    print(f"\n{len(SIZES)} panels in paper/figures/svg/{SUB}/")
    for stem, (w, h) in SIZES.items():
        print(f"  {stem:18s} {w:.2f} x {h:.2f} in  {WHAT[stem]}")


if __name__ == "__main__":
    main()
