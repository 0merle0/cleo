#!/usr/bin/env python3
"""Figure 1, one SVG per panel, for assembly by hand.

The assembled `fig1_method.py` exists and still builds. This writes the SAME
panels as eight separate files so the figure can be laid out in Inkscape
instead of in a gridspec. Both read from one set of panel functions, so a fix
to a panel lands in both and they cannot drift.

    uv run python paper/figures/fig1_panels.py
    -> paper/figures/svg/fig1_panels/*.svg

EACH PANEL IS AUTHORED AT THE SIZE IT IS MEANT TO BE PLACED AT, in inches on
a 6.5 in page. That is not cosmetic: a font size only means anything at final
size, so a panel authored 4 in wide and dropped in at 2 in arrives with 3.5 pt
labels. Place these at 100% and the 7 pt floor holds. If one has to be scaled
on the way in, scale the authored size here and rebuild rather than scaling
the SVG.

NO PANEL LETTERS. They are added at assembly, where the layout decides what
is (a) and what is (d). The filename carries the intended letter.

`tight=False` throughout, with explicit margins, so each file's canvas is
exactly the stated size -- a trimmed bbox makes the canvas depend on how far
a tick label happens to stick out, which is the opposite of what a grid of
hand-placed boxes wants.
"""

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import ame_arms as AA  # noqa: E402
import fig1_method as F1  # noqa: E402
from figio import save  # noqa: E402

SUB = "fig1_panels"

# (filename stem, width in, height in). Widths are the fractions of a 6.5 in
# page these panels occupy in the assembled version, so the set tiles.
SIZES = {
    "fig1a_landscapes": (6.50, 2.20),
    "fig1b_shuffling": (3.70, 2.05),
    "fig1c_objective": (2.25, 2.05),
    "fig1d_cost": (2.35, 2.00),
    "fig1e_tradeoff": (2.35, 2.00),
    "fig1f_foldcost": (2.00, 2.00),
    "fig1g_seqspace": (3.05, 2.05),
    "fig1h_granularity": (3.05, 2.05),
}

# Per-panel axes margins. A schematic wants the whole canvas; a plot needs
# room for its tick labels and axis titles.
MARGIN = {
    "fig1a_landscapes": dict(left=0.015, right=0.985, top=0.895, bottom=0.035),
    "fig1b_shuffling": dict(left=0.01, right=0.99, top=0.98, bottom=0.02),
    "fig1c_objective": dict(left=0.02, right=0.98, top=0.98, bottom=0.02),
    "fig1d_cost": dict(left=0.215, right=0.975, top=0.97, bottom=0.225),
    "fig1e_tradeoff": dict(left=0.205, right=0.975, top=0.97, bottom=0.185),
    "fig1f_foldcost": dict(left=0.265, right=0.975, top=0.97, bottom=0.215),
    "fig1g_seqspace": dict(left=0.145, right=0.985, top=0.97, bottom=0.175),
    "fig1h_granularity": dict(left=0.145, right=0.985, top=0.97, bottom=0.175),
}


WHAT = {
    "fig1a_landscapes": "three search strategies, one toy landscape (2D, from clean.pdf)",
    "fig1b_shuffling": "the shuffling step and the rotation rule",
    "fig1c_objective": "the per-fragment GRPO objective",
    "fig1d_cost": "library size vs DNA spend, whole gene and k=2/4/8",
    "fig1e_tradeoff": "diversity vs pass rate, stock -> post-trained",
    "fig1f_foldcost": "oracle calls vs library size: filter vs train",
    "fig1g_seqspace": "one PCA of one-hot sequences, M0097",
    "fig1h_granularity": "retention vs k, trained at each k",
}


def _manifest():
    """Write a README beside the panels.

    The folder is what gets opened and assembled from, so what each file is
    and how big it is belongs IN it, not only in this script.
    """
    out = [
        "# Figure 1, one SVG per panel",
        "",
        "Generated by `paper/figures/fig1_panels.py` -- do not hand-edit",
        "these in place if you intend to rebuild. Copy out, or edit and",
        "accept that a rebuild overwrites.",
        "",
        "**Each panel is authored at the size it is meant to be placed at,**",
        "in inches on a 6.5 in page. Place at 100% and the 7 pt font floor",
        "holds. Scaling one on the way in shrinks its text with it -- change",
        "the authored size in `SIZES` and rebuild instead.",
        "",
        "No panel letters: they are added at assembly, where the layout",
        "decides what is (a) and what is (d). The filename carries the",
        "intended letter.",
        "",
        "| file | size (in) | what it shows |",
        "|---|---|---|",
    ]
    for stem, (w, h) in SIZES.items():
        out.append(f"| `{stem}.svg` | {w:.2f} x {h:.2f} | {WHAT[stem]} |")
    out += [
        "",
        "`fig1a_landscapes` holds all three landscapes in ONE file on",
        "purpose. They share a single height normalisation, which is the",
        "panel's whole argument; as three files they could be scaled",
        "independently and a reader comparing peak heights would be reading",
        "an artefact of placement.",
        "",
        "The assembled version is `../main/fig1_method.svg`. Both are built",
        "from the same panel functions in `fig1_method.py`, so they cannot",
        "drift.",
        "",
    ]
    d = HERE / "svg" / SUB
    d.mkdir(parents=True, exist_ok=True)
    (d / "README.md").write_text("\n".join(out))


def _fig(stem):
    """-> (figure, axes) sized and margined for one panel."""
    fig = plt.figure(figsize=SIZES[stem])
    gs = fig.add_gridspec(1, 1, **MARGIN[stem])
    return fig, fig.add_subplot(gs[0, 0])


def _write(fig, stem):
    save(fig, stem, dpi=900, tight=False, subdir=SUB)
    plt.close(fig)


# ------------------------------------------------------------------ panels

def panel_a():
    """The three landscapes, the fitness key and the legend, in ONE file.

    Kept together because they are one panel: the key gives the contour
    shading its referent and the legend tells the reader what the open
    circles in the third landscape are. Split apart they would be three
    drawings that could be scaled independently, and a reader comparing
    peak shading across them would be reading an artefact of placement.
    """
    stem = "fig1a_landscapes"
    fig = plt.figure(figsize=SIZES[stem])
    gs = fig.add_gridspec(1, 1, **MARGIN[stem])
    F1.panel_landscapes(fig, gs[0, 0])
    _write(fig, stem)


def panel_b():
    stem = "fig1b_shuffling"
    fig, ax = _fig(stem)
    F1.panel_shuffle(ax)
    _write(fig, stem)


def panel_c():
    stem = "fig1c_objective"
    fig, ax = _fig(stem)
    F1.panel_objective(ax)
    _write(fig, stem)


def panel_d():
    stem = "fig1d_cost"
    fig, ax = _fig(stem)
    F1.panel_cost(ax)
    _write(fig, stem)


def panel_e(arms):
    stem = "fig1e_tradeoff"
    fig, ax = _fig(stem)
    F1.panel_tradeoff(ax, arms)
    _write(fig, stem)


def panel_f(_arms=None):
    stem = "fig1f_foldcost"
    fig, ax = _fig(stem)
    F1.panel_folds(ax)
    _write(fig, stem)


def panel_g(space, var, pz):
    stem = "fig1g_seqspace"
    fig, ax = _fig(stem)
    F1.panel_space(ax, space, var, pz)
    _write(fig, stem)


def panel_h():
    stem = "fig1h_granularity"
    fig, ax = _fig(stem)
    F1.panel_k(ax)
    _write(fig, stem)


def main():
    # Collected once: AA.collect() rarefies over 200 draws per arm and
    # collect_space() runs an SVD over ~1,200 one-hot sequences. Neither
    # should run eight times.
    arms = AA.collect()
    space, var, pz = F1.collect_space()

    panel_a()
    panel_b()
    panel_c()
    panel_d()
    panel_e(arms)
    panel_f()
    panel_g(space, var, pz)
    panel_h()

    _manifest()
    print(f"\n{len(SIZES)} panels in paper/figures/svg/{SUB}/")
    for stem, (w, h) in SIZES.items():
        print(f"  {stem:22s} {w:.2f} x {h:.2f} in  {WHAT[stem]}")


if __name__ == "__main__":
    main()
