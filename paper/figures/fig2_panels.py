#!/usr/bin/env python3
"""Figure 2, one SVG per panel, for assembly by hand.

Same arrangement as fig1_panels.py: the assembled `fig2_petase_design.py`
and these files are built from one set of panel functions, so a fix lands in
both and they cannot drift.

Each panel is authored at the size it is meant to be placed at, in inches on
a 6.5 in page. Place at 100% and the 7 pt font floor holds. No panel letters
-- they belong to the layout; the filename carries the intended one.

    uv run python paper/figures/fig2_panels.py
    -> paper/figures/svg/fig2_panels/*.svg
"""

import sys
from pathlib import Path

import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import fig2_petase_design as F2  # noqa: E402
import petase_design as PD  # noqa: E402
from figio import save  # noqa: E402

SUB = "fig2_panels"

SIZES = {
    "fig2a_paired": (3.40, 2.30),
    "fig2d_training": (6.50, 2.70),
    "fig2b_spread": (3.15, 2.10),
    "fig2c_slotdist": (4.10, 2.10),
}

MARGIN = {
    # Tall bottom margin: the term names are rotated 30 degrees and are the
    # longest text in the panel.
    "fig2a_paired": dict(left=0.155, right=0.985, top=0.975, bottom=0.300),
    "fig2d_training": dict(left=0.055, right=0.988, top=0.945, bottom=0.095),
    # Wide left margin: the y axis is reward-term NAMES, not numbers, and
    # "His NE2 - ester O" needs the room. Guessing this margin is how the
    # assembled draft clipped them to "2 - ester O".
    "fig2b_spread": dict(left=0.300, right=0.980, top=0.975, bottom=0.165),
    "fig2c_slotdist": dict(left=0.112, right=0.988, top=0.905, bottom=0.185),
}

WHAT = {
    "fig2a_paired": "every reward term, step 0 vs end, paired",
    "fig2d_training": "full training trajectories, naive at step 0",
    "fig2b_spread": "collapse in batch spread, naive vs post-trained",
    "fig2c_slotdist": "part menu per slot, by distance from the anchors",
}


def _fig(stem):
    fig = plt.figure(figsize=SIZES[stem])
    gs = fig.add_gridspec(1, 1, **MARGIN[stem])
    return fig, fig.add_subplot(gs[0, 0])


def _write(fig, stem):
    save(fig, stem, dpi=900, tight=False, subdir=SUB)
    plt.close(fig)


def panel_a():
    """Step 0 against the end, paired, every reward term on one axis."""
    stem = "fig2a_paired"
    fig, ax = _fig(stem)
    F2.panel_paired(ax)
    _write(fig, stem)


def panel_d():
    """The full trajectories. Kept because the paired panel compresses 211
    steps to two points and the shape of the approach is worth having."""
    stem = "fig2d_training"
    fig = plt.figure(figsize=SIZES[stem])
    gs = fig.add_gridspec(1, 1, **MARGIN[stem])
    F2.panel_training(fig, gs[0, 0])
    _write(fig, stem)


def panel_b():
    stem = "fig2b_spread"
    fig, ax = _fig(stem)
    F2.panel_spread(ax)
    _write(fig, stem)


def panel_c(menu):
    stem = "fig2c_slotdist"
    fig = plt.figure(figsize=SIZES[stem])
    gs = fig.add_gridspec(1, 1, **MARGIN[stem])
    F2.panel_slotdist(fig, gs[0, 0], menu)
    _write(fig, stem)


def _manifest():
    out = [
        "# Figure 2, one SVG per panel",
        "",
        "Generated by `paper/figures/fig2_panels.py`. Each panel is authored",
        "at the size it is meant to be placed at on a 6.5 in page -- place at",
        "100% and the 7 pt font floor holds. No panel letters: they belong to",
        "the layout, and the filename carries the intended one.",
        "",
        "| file | size (in) | what it shows |",
        "|---|---|---|",
    ]
    for stem, (w, h) in SIZES.items():
        out.append(f"| `{stem}.svg` | {w:.2f} x {h:.2f} | {WHAT[stem]} |")
    out += [
        "",
        "Two panels of Figure 2 are NOT here, because they are renders or",
        "need data that does not exist yet: the theozyme-to-momi design",
        "funnel, and the naive-vs-post-trained active-site clouds. The second",
        "needs both arms regenerated from the surviving checkpoints -- see",
        "the module docstring of `petase_design.py`.",
        "",
        "The assembled version is `../main/fig2_petase_design.svg`. Both are",
        "built from the same panel functions in `fig2_petase_design.py`.",
        "",
    ]
    d = HERE / "svg" / SUB
    d.mkdir(parents=True, exist_ok=True)
    (d / "README.md").write_text("\n".join(out))


def main():
    menu = PD.part_menu()
    panel_a()
    panel_b()
    panel_c(menu)
    panel_d()
    _manifest()
    print(f"\n{len(SIZES)} panels in paper/figures/svg/{SUB}/")
    for stem, (w, h) in SIZES.items():
        print(f"  {stem:18s} {w:.2f} x {h:.2f} in  {WHAT[stem]}")


if __name__ == "__main__":
    main()
